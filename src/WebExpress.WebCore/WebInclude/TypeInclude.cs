namespace WebExpress.WebCore.WebInclude
{
    /// <summary>
    /// The include kind specifies whether the include represents JavaScript or CSS.
    /// </summary>
    public enum TypeInclude
    {
        /// <summary>
        /// Represents the JavaScript programming language.
        /// </summary>
        JavaScript = 0,

        /// <summary>
        /// Represents a stylesheet resource, typically used to define the visual presentation of a document 
        /// or user interface.
        /// </summary>
        StyleSheet = 1
    }
}
