namespace WebExpress.WebCore.WebHtml
{
    /// <summary>
    /// Enumeration representing the different types of favicons.
    /// </summary>
    public enum TypeFavicon
    {
        /// <summary>
        /// The default favicon type.
        /// </summary>
        Default,

        /// <summary>
        /// Favicon type for .ico files.
        /// </summary>
        ICON,

        /// <summary>
        /// Favicon type for .png files.
        /// </summary>
        PNG,

        /// <summary>
        /// Favicon type for .jpg files.
        /// </summary>
        JPG,

        /// <summary>
        /// Favicon type for .svg files.
        /// </summary>
        SVG
    }
}
