namespace WebExpress.WebCore.WebUri
{
    /// <summary>
    /// The typ of the uri.
    /// </summary>
    public enum UriScheme
    {
        /// <summary>
        /// The File URI scheme.
        /// </summary>
        File,

        /// <summary>
        /// The FTP URI scheme.
        /// </summary>
        FTP,

        /// <summary>
        /// The HTTP URI scheme.
        /// </summary>
        Http,

        /// <summary>
        /// The HTTPS URI scheme.
        /// </summary>
        Https,

        /// <summary>
        /// The LDAP URI scheme.
        /// </summary>
        Ldap,

        /// <summary>
        /// The LDAPS URI scheme.
        /// </summary>
        Ldaps,

        /// <summary>
        /// The Mailto URI scheme.
        /// </summary>
        Mailto
    }
}